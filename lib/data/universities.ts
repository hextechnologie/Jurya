// Get all universities as a flat list
export function getAllUniversities(): string[] {
  return Object.values(universitiesByCountry).flat().sort()
}

// Search universities by query (fuzzy search)
export function searchUniversities(query: string, userCountry?: string): string[] {
  const lowerQuery = query.toLowerCase()
  const allUniversities = getAllUniversities()

  // Filter universities matching the query
  const matches = allUniversities.filter(uni =>
    uni.toLowerCase().includes(lowerQuery)
  )

  // If user has a country, prioritize universities from that country
  if (userCountry && universitiesByCountry[userCountry]) {
    const countryUniversities = universitiesByCountry[userCountry].filter(uni =>
      uni.toLowerCase().includes(lowerQuery)
    )
    const otherUniversities = matches.filter(uni => !countryUniversities.includes(uni))
    return [...countryUniversities, ...otherUniversities]
  }

  return matches
}

// Get universities by country
export function getUniversitiesByCountry(country: string): string[] {
  return universitiesByCountry[country] || []
}

// Get list of countries that have universities
export function getCountriesWithUniversities(): string[] {
  return Object.keys(universitiesByCountry).sort()
}
